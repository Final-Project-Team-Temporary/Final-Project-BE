def write_csv(output_file: str, all_terms: List[Tuple[str, str]]):
    """CSV 파일 작성"""
    with open(output_file, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        writer.writerow(['termName', 'termDescription'])

        for term_name, term_description in all_terms:
            writer.writerow([term_name, term_description])

